def resolve_region_candidates(address: Optional[str]) -> List[Tuple[str, str]]:
    """주소 문자열에서 (areaCd, signguCd) 후보들을 뽑는다.

    TourAPI의 areacode/sigungucode 필드 대신 주소를 파싱하는 이유는, 그 필드가
    비어 있는 레코드가 실제로 존재하기 때문이다(경복궁 등). addr1은 채워져 있다.

    보통 후보는 1개다. '경기도 수원시'처럼 자치구까지 없는 2단계 주소일 때만
    해당 시의 모든 구를 후보로 돌려준다 — 임의로 한 구를 고르면 틀린 값을 보여주게 된다.
    """
    if not address:
        return []

    tokens = address.split()
    if not tokens:
        return []

    area_cd = AREA_ALIASES.get(tokens[0])
    if area_cd is None:
        return []

    sgg_map = SIGUNGU_CODES.get(area_cd, {})
    if not sgg_map:
        return []

    # '수원시 팔달구'처럼 두 토큰이 한 시군구를 이루는 경우를 먼저 본다.
    if len(tokens) >= 3:
        two = f"{tokens[1]} {tokens[2]}"
        if two in sgg_map:
            return [(area_cd, sgg_map[two])]

    if len(tokens) >= 2 and tokens[1] in sgg_map:
        return [(area_cd, sgg_map[tokens[1]])]

    # 세종특별자치시: 시군구가 시도와 같아 주소에 시군구 토큰이 없다.
    if len(sgg_map) == 1:
        return [(area_cd, next(iter(sgg_map.values())))]

    # '경기도 수원시 ...'처럼 자치구가 빠진 주소 — 그 시의 구를 전부 후보로 둔다.
    if len(tokens) >= 2:
        prefix = tokens[1] + " "
        matches = [cd for nm, cd in sgg_map.items() if nm.startswith(prefix)]
        if matches:
            return [(area_cd, cd) for cd in matches]

    return []


def resolve_region(address: Optional[str]) -> Optional[Tuple[str, str]]:
    """후보가 여럿이면 첫 번째만. 단건 조회(상세페이지)용 편의 함수."""
    candidates = resolve_region_candidates(address)
    return candidates[0] if candidates else None
